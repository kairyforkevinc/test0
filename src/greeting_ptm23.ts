/**
 * Greeting utility module providing the greet_ptm23 function.
 */

/**
 * Returns a greeting string for the given name.
 * @param name - The name to greet
 * @returns A greeting in the format "Hello, {name}!"
 */
export function greet_ptm23(name: string): string {
  return "Hello, " + name + "!";
}
