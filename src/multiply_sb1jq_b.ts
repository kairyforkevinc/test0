/**
 * Math utility module providing multiplication operation.
 * This module contains the multiply_sb1jq_b function for multiplying two numbers.
 */

/**
 * Multiplies two numbers together.
 * @param a - The first number to multiply
 * @param b - The second number to multiply
 * @returns The product of a and b
 */
export function multiply_sb1jq_b(a: number, b: number): number {
  return a * b;
}
