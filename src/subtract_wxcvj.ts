/**
 * Math utility module providing subtraction operation.
 * This module contains the subtract_wxcvj function for subtracting two numbers.
 */

/**
 * Subtracts the second number from the first.
 * @param a - The number to subtract from
 * @param b - The number to subtract
 * @returns The difference of a and b
 */
export function subtract_wxcvj(a: number, b: number): number {
  return a - b;
}
