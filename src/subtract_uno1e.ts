/**
 * Math utility module providing subtraction operation.
 * This module contains the subtract_uno1e function for subtracting two numbers.
 */

/**
 * Subtracts the second number from the first number.
 * @param a - The first number (minuend)
 * @param b - The second number (subtrahend)
 * @returns The difference of a and b
 */
export function subtract_uno1e(a: number, b: number): number {
  return a - b;
}
